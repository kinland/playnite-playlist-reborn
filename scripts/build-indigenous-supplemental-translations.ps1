function Merge-Hltb {
    param([hashtable]$Locale)
    foreach ($key in $hltb.Keys) {
        if (-not $Locale.ContainsKey($key)) {
            $Locale[$key] = $hltb[$key]
        }
    }
    return $Locale
}

